-- Tabela de Pautas
CREATE TABLE pauta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao VARCHAR(1000),
    criada_em TIMESTAMP NOT NULL
);

-- Tabela de Sessões de Votação
CREATE TABLE sessao_votacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pauta_id BIGINT NOT NULL,
    data_abertura TIMESTAMP NOT NULL,
    data_fechamento TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    criada_em TIMESTAMP NOT NULL,
    CONSTRAINT fk_sessao_pauta FOREIGN KEY (pauta_id) REFERENCES pauta(id) ON DELETE CASCADE,
    CONSTRAINT uk_sessao_pauta UNIQUE (pauta_id)
);

-- Tabela de Votos
CREATE TABLE voto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id BIGINT NOT NULL,
    cpf_associado VARCHAR(14) NOT NULL,
    opcao VARCHAR(10) NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    CONSTRAINT fk_voto_sessao FOREIGN KEY (sessao_id) REFERENCES sessao_votacao(id) ON DELETE CASCADE,
    CONSTRAINT uk_voto_sessao_associado UNIQUE (sessao_id, cpf_associado)
);

-- Índices para otimização de consultas e alta concorrência
CREATE INDEX idx_sessao_status_datas ON sessao_votacao(status, data_fechamento);
CREATE INDEX idx_voto_sessao_opcao ON voto(sessao_id, opcao);
CREATE INDEX idx_voto_cpf ON voto(cpf_associado);
